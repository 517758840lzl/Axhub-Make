String t(AppLocale locale, String key, [Map<String, String>? params]) {
  final map = switch (locale) {
    AppLocale.zhCN => _zh,
    AppLocale.en => _en,
    AppLocale.es => _es,
  };
  var s = map[key] ?? _zh[key] ?? key;
  if (params != null) {
    params.forEach((k, v) {
      s = s.split('{$k}').join(v);
    });
  }
  return s;
}

